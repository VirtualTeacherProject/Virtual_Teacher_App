-- SCRUM-50: baseline of the schema that Hibernate (ddl-auto=update) had built up
-- to and including SCRUM-20.
--
-- Runs on H2 and PostgreSQL. Every statement is "if not exists" on purpose:
-- databases that existed before Flyway are baselined at version 0, so this
-- script also runs on them. It leaves their tables alone and only creates what
-- is missing. It does NOT add missing columns or change existing ones.
--
-- From V2 on, migrations are ordinary scripts: never edit a migration that has
-- been applied anywhere, add a new one.

create table if not exists users (
    user_id          bigint generated by default as identity primary key,
    email            varchar(254) not null,
    password         varchar(100) not null,
    first_name       varchar(50)  not null,
    last_name        varchar(50)  not null,
    profile_picture  varchar(255),
    role             varchar(20)  not null,
    status           varchar(20)  not null,
    teacher_approved boolean      not null,
    constraint uk_users_email unique (email),
    constraint ck_users_role check (role in ('TEACHER', 'STUDENT', 'ADMIN'))
);

create table if not exists courses (
    course_id     bigint generated by default as identity primary key,
    title         varchar(100) not null,
    topic         varchar(250) not null,
    description   varchar(1000),
    passing_grade float(53),
    start_date    timestamp(6),
    status        varchar(20)  not null,
    teacher_id    bigint       not null,
    constraint fk_courses_teacher foreign key (teacher_id) references users (user_id)
);

create table if not exists lectures (
    lecture_id           bigint generated by default as identity primary key,
    title                varchar(120)  not null,
    description          varchar(1000) not null,
    video_url            varchar(500)  not null,
    assignment_file_path varchar(50)   not null,
    course_id            bigint        not null,
    constraint fk_lectures_course foreign key (course_id) references courses (course_id)
);

create table if not exists enrollments (
    enrollment_id     bigint generated by default as identity primary key,
    student_id        bigint       not null,
    course_id         bigint       not null,
    average_grade     float(53),
    completion_status varchar(30)  not null,
    enrolled_at       timestamp(6) not null,
    rating            integer,
    review_text       varchar(1000),
    rated_at          timestamp(6),
    constraint fk_enrollments_student foreign key (student_id) references users (user_id),
    constraint fk_enrollments_course foreign key (course_id) references courses (course_id),
    constraint ck_enrollments_completion_status
        check (completion_status in ('IN_PROGRESS', 'COMPLETED', 'DROPPED'))
);

create table if not exists assignments (
    assignment_id        bigint generated by default as identity primary key,
    student_id           bigint       not null,
    lecture_id           bigint       not null,
    submission_file_path varchar(255) not null,
    grade                float(53),
    comment              varchar(500),
    student_comment      varchar(500),
    teacher_comment      varchar(500),
    submitted_at         timestamp(6) not null,
    constraint fk_assignments_student foreign key (student_id) references users (user_id),
    constraint fk_assignments_lecture foreign key (lecture_id) references lectures (lecture_id)
);

-- LectureComment ids come from a sequence (Hibernate allocates 50 at a time).
create sequence if not exists lecture_comments_seq start with 1 increment by 50;

create table if not exists lecture_comments (
    comment_id bigint        not null primary key,
    lecture_id bigint        not null,
    user_id    bigint        not null,
    comment    varchar(1000) not null,
    created_at timestamp(6),
    constraint fk_lecture_comments_lecture foreign key (lecture_id) references lectures (lecture_id),
    constraint fk_lecture_comments_user foreign key (user_id) references users (user_id)
);

create table if not exists lecture_notes (
    note_id    bigint generated by default as identity primary key,
    lecture_id bigint        not null,
    user_id    bigint        not null,
    content    varchar(5000) not null,
    updated_at timestamp(6),
    constraint fk_lecture_notes_lecture foreign key (lecture_id) references lectures (lecture_id),
    constraint fk_lecture_notes_user foreign key (user_id) references users (user_id),
    constraint uk_lecture_notes_lecture_user unique (lecture_id, user_id)
);
