-- SCRUM-28: attendance tracker for courses that require attendance (SCRUM-45).
-- One row per lecture and enrolled student, written when the teacher saves the
-- roll call; status is PRESENT or ABSENT. No row means attendance was not taken yet.
create table lecture_attendance (
    attendance_id bigint generated by default as identity primary key,
    lecture_id    bigint       not null,
    student_id    bigint       not null,
    status        varchar(20)  not null,
    recorded_at   timestamp(6) not null,
    constraint fk_lecture_attendance_lecture foreign key (lecture_id) references lectures (lecture_id),
    constraint fk_lecture_attendance_student foreign key (student_id) references users (user_id),
    constraint uk_lecture_attendance_lecture_student unique (lecture_id, student_id)
);
