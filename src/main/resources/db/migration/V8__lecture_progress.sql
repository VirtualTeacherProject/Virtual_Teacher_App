-- SCRUM-51 part B: self-paced lecture completion and optional in-order lectures.

-- Lecture order within a course; existing lectures keep their id order.
alter table lectures add column lecture_order integer;
update lectures set lecture_order = (
    select count(*) from lectures l2
    where l2.course_id = lectures.course_id and l2.lecture_id <= lectures.lecture_id);
alter table lectures alter column lecture_order set not null;

-- Whether a lecture has an assignment; assignment_file_path is free text, so
-- lectures where it was filled in are taken to have one.
alter table lectures add column assignment_required boolean default false not null;
update lectures set assignment_required = true where trim(assignment_file_path) <> '';

-- Courses whose lectures must be completed in order.
alter table courses add column lectures_in_order boolean default false not null;

-- One row per student and lecture they marked as finished.
create table lecture_progress (
    progress_id bigint generated by default as identity primary key,
    lecture_id  bigint       not null,
    student_id  bigint       not null,
    finished_at timestamp(6) not null,
    constraint fk_lecture_progress_lecture foreign key (lecture_id) references lectures (lecture_id),
    constraint fk_lecture_progress_student foreign key (student_id) references users (user_id),
    constraint uk_lecture_progress_lecture_student unique (lecture_id, student_id)
);

-- Lectures that already have a graded submission count as finished, so students
-- who completed a course before this migration stay completed.
insert into lecture_progress (lecture_id, student_id, finished_at)
select lecture_id, student_id, max(submitted_at)
from assignments
where grade is not null
group by lecture_id, student_id;
