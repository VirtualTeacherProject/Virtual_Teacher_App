-- SCRUM-35: enrolled students ask the teacher for additional resources.
-- status is OPEN for now; SCRUM-36 adds the other states (no migration needed).
create table resource_requests (
    request_id bigint generated by default as identity primary key,
    course_id  bigint        not null,
    student_id bigint        not null,
    message    varchar(2000) not null,
    status     varchar(20)   not null,
    created_at timestamp(6)  not null,
    constraint fk_resource_requests_course foreign key (course_id) references courses (course_id),
    constraint fk_resource_requests_student foreign key (student_id) references users (user_id)
);
