-- SCRUM-34: additional resources (links) a teacher attaches to a course.
create table course_resources (
    resource_id bigint generated by default as identity primary key,
    course_id   bigint       not null,
    title       varchar(120) not null,
    url         varchar(500) not null,
    description varchar(1000),
    created_at  timestamp(6) not null,
    constraint fk_course_resources_course foreign key (course_id) references courses (course_id)
);
