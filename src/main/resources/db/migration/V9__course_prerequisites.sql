-- SCRUM-48: prerequisite courses. A required prerequisite (same topic) must be
-- completed before a student can enrol; a recommended one (any topic) is only shown.
create table course_prerequisites (
    prerequisite_id    bigint generated by default as identity primary key,
    course_id          bigint  not null,
    required_course_id bigint  not null,
    required           boolean default false not null,
    constraint fk_course_prerequisites_course foreign key (course_id) references courses (course_id),
    constraint fk_course_prerequisites_required_course foreign key (required_course_id) references courses (course_id),
    constraint uk_course_prerequisites_pair unique (course_id, required_course_id)
);
